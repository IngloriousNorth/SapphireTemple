let leisureImage = leisureImages[0];

function canon(QRNG) {
    console.log(QRNG);
    const candidateArr = leisureImages.filter(e =>
        leisureImages.some(a =>
            a !== e && e.attributes.some(attr => a.attributes.includes(attr))
        )
    );
    return candidateArr[QRNG % candidateArr.length];
}

async function fetchAndReveal() {
    try {
        const res = await fetch("https://qrngproxy.vercel.app/api/proxy");
        const data = await res.json();
        console.info(data);
        
        // data.qrn is parsed from hex directly into an integer
        const randomInt = parseInt(data.qrn, 16);
        const selectedSlide = canon(randomInt);
        
        if (selectedSlide) {
            reveal(selectedSlide);
        }
    } catch (err) {
        console.error("Failed to fetch QRNG:", err);
    }
}

async function init() {
    reveal(leisureImages[0]);
    setInterval(fetchAndReveal, 6667);
}

function reveal(slide) {
    const theatre = document.getElementsByClassName("theatre")[0];
    theatre.innerHTML = `<img src="image/${slide.src}" alt=""><br><p>${slide.text}</p>`;
}